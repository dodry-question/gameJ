/**
 * ТИПЫ ИГРОВОГО СЛОТА — это контракт между меню и любой игрой.
 *
 * Меню умеет только одно: показать игру и вернуться назад. Поэтому игре
 * отдаётся контейнер (пустой div) и колбэк onExit — когда игрок захочет выйти.
 */
export interface GameContext {
  /** Вызывать, когда игрок захотел вернуться в меню (например, нажал Esc) */
  onExit: () => void
}

export interface GameHandle {
  /** Полностью убрать игру: слушатели, rAF, DOM. Вызывается при выходе из экрана. */
  destroy: () => void
}
