import { chromium } from 'playwright-core'
const browser = await chromium.launch({
  executablePath: 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',
  args: ['--enable-unsafe-swiftshader', '--use-gl=angle', '--autoplay-policy=no-user-gesture-required'],
})
const page = await browser.newPage({ viewport: { width: 1000, height: 760 } })
page.on('pageerror', (e) => console.log('[pageerror]', String(e)))
await page.goto('http://127.0.0.1:5199/?ui&cam', { waitUntil: 'networkidle' })
await page.mouse.click(480, 360)
await page.waitForFunction(() => window.__cctv?.loaded === true, null, { timeout: 30000 })
await page.waitForTimeout(800)
await page.evaluate(() => window.__tds.reset())
await page.waitForTimeout(500)
console.log('узел 01:', JSON.stringify(await page.evaluate(() => window.__tds.debugInfo().cam)))
console.log('windows:', JSON.stringify(await page.evaluate(() => window.__desk.windows.map((w) => ({ key: w.key, x: w.x, y: w.y, w: w.w, h: w.h, min: w.min })))))
const n1 = await page.evaluate(() => window.__tds.debugInfo().cam)
await page.mouse.move(n1.x, n1.y)
await page.mouse.down()
await page.waitForTimeout(600)
console.log('во время удержания:', JSON.stringify(await page.evaluate(() => ({ s: window.__tds.debugInfo().screen, ch: window.__tds.debugInfo().channel }))))
await page.waitForTimeout(1200)
await page.mouse.up()
await page.waitForTimeout(600)
console.log('после:', JSON.stringify(await page.evaluate(() => ({ screen: window.__tds.debugInfo().screen, ch: window.__tds.debugInfo().channel, error: window.__tds.debugInfo().error }))))
await browser.close()
